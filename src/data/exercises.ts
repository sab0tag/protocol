// D60: the kettlebell library — three levels, each exercise with two schematic poses (side view, facing right:
// «Початок» and «Рух»), the path of the bell, and the words a coach would say. Poses are points in a 100 × 120 box
// (ground at y = 114). Default targets are a start, not a prescription: the person and the doctor adjust them.

export type P = [number, number];
export interface Pose {
  head: P; sh: P; hip: P; knee: P; ankle: P; elbow: P; hand: P;
  knee2?: P; ankle2?: P; elbow2?: P; hand2?: P; // the other leg / arm when it is apart
  kb?: P; // the bell's centre
}
export type Level = 1 | 2 | 3;
export type Pattern = 'squat' | 'hinge' | 'push' | 'pull' | 'carry' | 'core' | 'getup';

export interface Exercise {
  id: string;
  name: string;
  level: Level;
  pattern: Pattern;
  unilateral: boolean;
  timed: boolean;
  sets: number;
  target: string; // what the plan of the set says («3 × 10 кожною»)
  start: string; // «Вихідна позиція»
  move: string; // «Рух»
  path: string; // «Амплітуда і напрям»
  cues: string[];
  mistakes: string[];
  caution?: string;
  poses: [Pose, Pose];
  arrow?: { from: P; to: P; via?: P }; // default: the bell from pose 1 to pose 2 (or the hips)
  /** D62: real photos where there are free ones (attribution required) — shown instead of the schematic figures. */
  photos?: { start: string; move: string; credit: string; source: string };
}

